package com.autism_rehablito_app.entity;

import jakarta.persistence.*;
import java.math.BigDecimal;
import java.time.LocalDateTime;

@Entity
@Table(
        name = "payments",
        uniqueConstraints = {
                @UniqueConstraint(
                        name = "uk_payment_razorpay_order_id",
                        columnNames = "razorpay_order_id"
                ),
                @UniqueConstraint(
                        name = "uk_payment_razorpay_payment_id",
                        columnNames = "razorpay_payment_id"
                ),
                @UniqueConstraint(
                        name = "uk_payment_receipt_reference",
                        columnNames = "receipt_reference"
                )
        }
)
public class Payment {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /*
     * Parent who made the payment.
     */
    @ManyToOne(optional = false)
    @JoinColumn(name = "parent_id", nullable = false)
    private Parent parent;

    /*
     * Child for whom the therapy payment is being made.
     */
    @ManyToOne(optional = false)
    @JoinColumn(name = "child_id", nullable = false)
    private Child child;

    /*
     * Snapshot of the therapy type at the time of payment.
     *
     * Examples:
     * Occupational Therapy
     * Speech Therapy
     * Both Occupational + Speech Therapy
     */
    @Column(name = "therapy_type", nullable = false, length = 100)
    private String therapyType;

    /*
     * Original fee calculated by backend.
     */
    @Column(name = "actual_fee", nullable = false, precision = 12, scale = 2)
    private BigDecimal actualFee;

    /*
     * Discount amount.
     *
     * Parent Razorpay payment:
     * discount = 0
     *
     * Future Admin payment can use this field.
     */
    @Column(name = "discount", nullable = false, precision = 12, scale = 2)
    private BigDecimal discount = BigDecimal.ZERO;

    /*
     * Final amount payable after discount.
     *
     * Formula:
     * finalPayable = actualFee - discount
     */
    @Column(name = "final_payable", nullable = false, precision = 12, scale = 2)
    private BigDecimal finalPayable;

    /*
     * Actual amount successfully paid.
     */
    @Column(name = "paid_amount", nullable = false, precision = 12, scale = 2)
    private BigDecimal paidAmount = BigDecimal.ZERO;

    /*
     * Currency used for payment.
     */
    @Column(name = "currency", nullable = false, length = 10)
    private String currency = "INR";

    /*
     * Razorpay order ID generated by backend.
     */
    @Column(name = "razorpay_order_id", unique = true, length = 100)
    private String razorpayOrderId;

    /*
     * Razorpay payment ID returned after payment.
     */
    @Column(name = "razorpay_payment_id", unique = true, length = 100)
    private String razorpayPaymentId;

    /*
     * Razorpay payment signature used for secure verification.
     */
    @Column(name = "razorpay_signature", length = 500)
    private String razorpaySignature;

    /*
     * Payment lifecycle status.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "payment_status", nullable = false, length = 20)
    private PaymentStatus status = PaymentStatus.PENDING;

    /*
     * Successful payment date/time.
     */
    @Column(name = "payment_date")
    private LocalDateTime paymentDate;

    /*
     * Internal receipt/reference number.
     *
     * Example:
     * AC-PAY-2026-000001
     */
    @Column(name = "receipt_reference", unique = true, length = 100)
    private String receiptReference;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    @PrePersist
    protected void onCreate() {

        LocalDateTime now = LocalDateTime.now();

        createdAt = now;
        updatedAt = now;

        if (discount == null) {
            discount = BigDecimal.ZERO;
        }

        if (paidAmount == null) {
            paidAmount = BigDecimal.ZERO;
        }

        if (currency == null || currency.isBlank()) {
            currency = "INR";
        }

        if (status == null) {
            status = PaymentStatus.PENDING;
        }
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = LocalDateTime.now();

        if (discount == null) {
            discount = BigDecimal.ZERO;
        }

        if (paidAmount == null) {
            paidAmount = BigDecimal.ZERO;
        }

        if (currency == null || currency.isBlank()) {
            currency = "INR";
        }

        if (status == null) {
            status = PaymentStatus.PENDING;
        }
    }

    public Long getId() {
        return id;
    }

    public Parent getParent() {
        return parent;
    }

    public void setParent(Parent parent) {
        this.parent = parent;
    }

    public Child getChild() {
        return child;
    }

    public void setChild(Child child) {
        this.child = child;
    }

    public String getTherapyType() {
        return therapyType;
    }

    public void setTherapyType(String therapyType) {
        this.therapyType = therapyType;
    }

    public BigDecimal getActualFee() {
        return actualFee;
    }

    public void setActualFee(BigDecimal actualFee) {
        this.actualFee = actualFee;
    }

    public BigDecimal getDiscount() {
        return discount;
    }

    public void setDiscount(BigDecimal discount) {
        this.discount = discount;
    }

    public BigDecimal getFinalPayable() {
        return finalPayable;
    }

    public void setFinalPayable(BigDecimal finalPayable) {
        this.finalPayable = finalPayable;
    }

    public BigDecimal getPaidAmount() {
        return paidAmount;
    }

    public void setPaidAmount(BigDecimal paidAmount) {
        this.paidAmount = paidAmount;
    }

    public String getCurrency() {
        return currency;
    }

    public void setCurrency(String currency) {
        this.currency = currency;
    }

    public String getRazorpayOrderId() {
        return razorpayOrderId;
    }

    public void setRazorpayOrderId(String razorpayOrderId) {
        this.razorpayOrderId = razorpayOrderId;
    }

    public String getRazorpayPaymentId() {
        return razorpayPaymentId;
    }

    public void setRazorpayPaymentId(String razorpayPaymentId) {
        this.razorpayPaymentId = razorpayPaymentId;
    }

    public String getRazorpaySignature() {
        return razorpaySignature;
    }

    public void setRazorpaySignature(String razorpaySignature) {
        this.razorpaySignature = razorpaySignature;
    }

    public PaymentStatus getStatus() {
        return status;
    }

    public void setStatus(PaymentStatus status) {
        this.status = status;
    }

    public LocalDateTime getPaymentDate() {
        return paymentDate;
    }

    public void setPaymentDate(LocalDateTime paymentDate) {
        this.paymentDate = paymentDate;
    }

    public String getReceiptReference() {
        return receiptReference;
    }

    public void setReceiptReference(String receiptReference) {
        this.receiptReference = receiptReference;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }
}